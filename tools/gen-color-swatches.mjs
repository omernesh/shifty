#!/usr/bin/env node
// tools/gen-color-swatches.mjs
// Emits app/blocks/color_swatches.yaml from the FROZEN PALETTE in
// app/plugins/shifty-roster/src/helpers/palette.js (single source of truth).
//
// Plan 02-06 Task 2 (UI-SPEC §"Reusable Components — 4. 24-swatch color picker").
//
// The output is a single Lowdefy Box block id `color_swatches` containing 24
// circular swatch_N child blocks (4 rows × 6 cols). Each swatch:
//   - 32×32px circle, hex backgroundColor from PALETTE[N]
//   - 1px #D9D9D9 border by default, 3px #000000 border when
//     selected_color_index state equals N
//   - onClick → SetState selected_color_index + selected_color_hex
//
// Deterministic: re-running produces byte-identical output (no timestamps,
// stable iteration order, no random IDs).
//
// Usage:
//   node tools/gen-color-swatches.mjs

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { PALETTE } from '../app/plugins/shifty-roster/src/helpers/palette.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = resolve(__dirname, '..', 'app', 'blocks', 'color_swatches.yaml');

function emit() {
  const lines = [];
  lines.push('# AUTO-GENERATED by tools/gen-color-swatches.mjs — DO NOT EDIT BY HAND.');
  lines.push('# Source of truth: PALETTE in app/plugins/shifty-roster/src/helpers/palette.js.');
  lines.push('# Re-run with: node tools/gen-color-swatches.mjs');
  lines.push('#');
  lines.push('# Reusable 24-swatch color picker. _ref\'d from:');
  lines.push('#   - app/pages/admin/soldier_detail.yaml (Card: צבע אישי)');
  lines.push('#   - app/pages/admin/my_profile.yaml (future — D-16)');
  lines.push('#');
  lines.push('# State contract:');
  lines.push('#   - reads:  _state.selected_color_index (integer 0..23)');
  lines.push('#   - writes: _state.selected_color_index + _state.selected_color_hex on click');
  lines.push('');
  lines.push('id: color_swatches');
  lines.push('type: Box');
  lines.push('layout:');
  lines.push('  contentGutter: [8, 8]');
  lines.push('  contentWrap: wrap');
  lines.push('  contentJustify: flex-start');
  lines.push('style:');
  lines.push('  maxWidth: 256');
  lines.push('  padding: 16');
  lines.push('blocks:');
  for (let i = 0; i < PALETTE.length; i++) {
    const hex = PALETTE[i];
    lines.push(`  - id: swatch_${i}`);
    lines.push('    type: Box');
    lines.push('    style:');
    lines.push('      width: 32');
    lines.push('      height: 32');
    lines.push('      borderRadius: 16');
    lines.push('      cursor: pointer');
    lines.push(`      backgroundColor: '${hex}'`);
    lines.push('      border:');
    lines.push('        _if:');
    lines.push(`          test: { _eq: [{ _state: selected_color_index }, ${i}] }`);
    lines.push("          then: '3px solid #000000'");
    lines.push("          else: '1px solid #D9D9D9'");
    lines.push('    events:');
    lines.push('      onClick:');
    lines.push('        - id: pick');
    lines.push('          type: SetState');
    lines.push('          params:');
    lines.push(`            selected_color_index: ${i}`);
    lines.push(`            selected_color_hex: '${hex}'`);
  }
  lines.push('');
  return lines.join('\n');
}

const out = emit();
writeFileSync(OUT_PATH, out, 'utf-8');
console.log(`Wrote ${OUT_PATH} (${PALETTE.length} swatches, ${out.length} bytes).`);
